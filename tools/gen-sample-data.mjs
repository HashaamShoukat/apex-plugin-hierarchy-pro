// Generates demo/sample_data.sql from demo/mock-data.js: table HCP_DEMO_EMPLOYEES
// with ~150 people (English and Arabic names, departments, colours, vacancies).
//   node tools/gen-sample-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const ctx = { window: {} };
vm.runInNewContext(readFileSync("demo/mock-data.js", "utf8"), ctx);
const M = ctx.window.HCP_MOCK;
const en = M.org("en"), ar = M.org("ar");
const c = Object.fromEntries(en.cols.map((n, i) => [n, i]));

const q = v => {
    if (v === null || v === undefined || v === "") return "null";
    const s = String(v);
    if (/^[\x20-\x7e]*$/.test(s)) return "'" + s.replace(/'/g, "''") + "'";
    let u = "";
    for (const ch of s) {
        const k = ch.codePointAt(0);
        u += k < 128 && ch !== "\\" && ch !== "'" ? ch : "\\" + k.toString(16).toUpperCase().padStart(4, "0");
    }
    return "unistr('" + u + "')";
};

let ins = "";
en.rows.forEach((r, i) => {
    const a = ar.rows[i];
    ins += `insert into hcp_demo_employees values (${r[c.NODE_ID]}, ${r[c.PARENT_ID] || "null"}, ${q(r[c.TITLE])}, ${q(a[c.TITLE])}, ` +
        `${q(r[c.SUBTITLE])}, ${q(a[c.SUBTITLE])}, ${q(r[c.LEGEND])}, ${q(a[c.LEGEND])}, ${q(r[c.NODE_COLOR])}, ${q(r[c.LOCATION])}, ` +
        `${q(r[c.GRADE])}, date '${r[c.JOINED] || "2020-01-01"}', ${q(r[c.EMAIL])}, ${r[c.SALARY] || "null"}, '${r[c.HIGHLIGHT] === "Y" ? "Y" : "N"}');\n`;
});

writeFileSync("demo/sample_data.sql", `--------------------------------------------------------------------------------
-- Hierarchy Pro - demo data (generated by tools/gen-sample-data.mjs)
-- ${en.rows.length} people in 6 departments, English and Arabic names, vacancies flagged.
--   @sample_data.sql
--------------------------------------------------------------------------------
set define off
whenever sqlerror continue
drop table hcp_demo_employees purge;
whenever sqlerror exit failure rollback

create table hcp_demo_employees (
    emp_id        number         primary key,
    manager_id    number         references hcp_demo_employees,
    name_en       varchar2(100)  not null,
    name_ar       varchar2(100),
    job_en        varchar2(100),
    job_ar        varchar2(100),
    department_en varchar2(100),
    department_ar varchar2(100),
    dept_color    varchar2(20),
    location      varchar2(50),
    grade         varchar2(20),
    hire_date     date,
    email         varchar2(100),
    salary        number,
    is_vacant     varchar2(1)    default 'N' not null
);

create index hcp_demo_employees_mgr on hcp_demo_employees (manager_id);

${ins}
commit;

prompt
prompt Region source for an org chart (Arabic: use name_ar / job_ar / department_ar):
prompt
prompt   select emp_id        as node_id,
prompt          manager_id    as parent_id,
prompt          name_en       as title,
prompt          job_en        as subtitle,
prompt          dept_color    as node_color,
prompt          department_en as legend,
prompt          is_vacant     as highlight,
prompt          location, grade, hire_date, salary
prompt     from hcp_demo_employees
`);
console.log(en.rows.length + " rows written");
