// Generates db/text_messages_en_ar.sql: every UI text of the plug-in as an APEX
// text message HCP.<KEY>, in English (from the defaults in the JS source) and
// Arabic (tools/messages_ar.json). Arabic is written with UNISTR so the script
// is pure ASCII and survives any client character set.
//   node tools/gen-messages.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/js/hierarchyChartPro.js", "utf8");
const block = /const MSG = \{([\s\S]*?)\n\};/.exec(src)[1];
const en = {};
for (const m of block.matchAll(/^\s*(\w+): "((?:[^"\\]|\\.)*)"/gm)) en[m[1]] = JSON.parse('"' + m[2] + '"');
const ar = JSON.parse(readFileSync("tools/messages_ar.json", "utf8"));

const sqlText = s => {
    if (/^[\x20-\x7e]*$/.test(s)) return "'" + s.replace(/'/g, "''") + "'";
    let u = "";
    for (const ch of s) {
        const c = ch.codePointAt(0);
        u += c < 128 && ch !== "\\" && ch !== "'" ? ch : "\\" + c.toString(16).toUpperCase().padStart(4, "0");
    }
    return "unistr('" + u + "')";
};

const missing = Object.keys(en).filter(k => !ar[k]);
if (missing.length) throw new Error("no Arabic text for " + missing.join(", "));

let rows = "";
for (const k of Object.keys(en)) {
    rows += `    add('${k}', ${sqlText(en[k])}, ${sqlText(ar[k])});\n`;
}

writeFileSync("db/text_messages_en_ar.sql", `--------------------------------------------------------------------------------
-- Hierarchy Pro - translatable UI text (generated by tools/gen-messages.mjs)
--
-- Creates / replaces text messages HCP.<KEY> in English (en) and Arabic (ar)
-- for one application. The plug-in sends the message for the session language
-- to the browser; keys without a message fall back to the built-in English.
--
-- Run as the application's parsing schema (APEX 24.1+):
--   @text_messages_en_ar.sql <application id>
-- Add more languages by copying an add() line per key with another language code.
--------------------------------------------------------------------------------
set define '&' verify off
whenever sqlerror exit failure rollback

declare
    l_app number := to_number('&1');

    procedure put ( p_key in varchar2, p_lang in varchar2, p_text in varchar2 )
    is
        l_id number;
    begin
        select translation_entry_id into l_id
          from apex_application_translations
         where application_id = l_app
           and translatable_message = 'HCP.' || p_key
           and language_code = p_lang;
        apex_lang.update_message(p_id => l_id, p_message_text => p_text);
    exception
        when no_data_found then
            apex_lang.create_message(
                p_application_id => l_app,
                p_name           => 'HCP.' || p_key,
                p_language       => p_lang,
                p_message_text   => p_text );
    end put;

    procedure add ( p_key in varchar2, p_en in varchar2, p_ar in varchar2 )
    is
    begin
        put(p_key, 'en', p_en);
        put(p_key, 'ar', p_ar);
    end add;
begin
    -- text messages need a workspace context
    for w in ( select workspace_id from apex_applications where application_id = l_app ) loop
        apex_util.set_security_group_id(w.workspace_id);
    end loop;

${rows}    commit;
end;
/
`);
console.log(Object.keys(en).length + " keys written");
